"""Waveform factory: describe a signal by its parameters, get the samples for a given sample rate

A waveform is a dataclass whose fields are its parameters. The same description serves a device that computes the
signal itself from parameters and one that needs the samples (:meth:`Waveform.realize`). Fields with a ``unit`` are
numbers expressed in that unit (SI: V, s, Hz, degrees for a phase); a pint quantity is accepted when creating the
waveform and converted.

:class:`WaveformFactory` is a PyMoDAQ :class:`~pymodaq_utils.factory.ObjectFactory`: it gives the forms by name, so an
application can offer them in a list (``WaveformFactory.names()``) and create one (``WaveformFactory().get('sine',
frequency=1e3)``), and a plugin package can add its own::

    @WaveformFactory.register('gaussian')
    @dataclasses.dataclass
    class Gaussian(Waveform):
        center: float = waveform_field(1e-3, 's', 'Center')
        width: float = waveform_field(1e-4, 's', 'Width')
        duration: float = waveform_field(2e-3, 's', 'Duration')

        def _realize(self, sample_rate):
            t = np.arange(self.n_samples(sample_rate)) / sample_rate
            return np.exp(-((t - self.center) / self.width) ** 2 / 2), None

The contract with the applications and the plugins is :data:`WAVEFORM_VERSION`; evolution rule: only add forms and
optional fields, never rename or remove one; a breaking change increments :data:`WAVEFORM_VERSION`.

The forms live in the other modules of this package, which register themselves in the factory when imported (the
``__init__`` imports them all).
"""
import dataclasses
from abc import ABC, abstractmethod
from typing import Any, ClassVar, Optional, Type, Union

import numpy as np

from pymodaq_data import Q_
from pymodaq_utils.factory import ObjectFactory

WAVEFORM_VERSION = 1


def waveform_field(default: Any, unit: Optional[str] = None, title: str = '', min: Optional[float] = None,
                   max: Optional[float] = None, tip: str = '') -> Any:
    """A dataclass field that is a parameter of the waveform

    Parameters
    ----------
    default: the default value
    unit: the unit of the number (pint syntax), None for a text
    title: the label of the parameter in the settings
    min, max: bounds of the parameter in the settings (and checked when the samples are computed)
    tip: help shown on the parameter
    """
    return dataclasses.field(default=default, metadata=dict(unit=unit, title=title, min=min, max=max, tip=tip))


@dataclasses.dataclass(frozen=True)
class RealizedWaveform:
    """The samples of a waveform for one sample rate

    Attributes
    ----------
    samples: the signal, in volts for a voltage output. One period for a periodic waveform (to be repeated), the whole
        signal otherwise
    sample_rate: Hz
    periodic: True if ``samples`` is one period to repeat
    frequency: Hz, the frequency that is really generated by repeating ``samples`` (periodic waveform only). It is the
        requested one rounded so that a period has a whole number of samples
    frequency_error: Hz, ``frequency`` minus the requested frequency
    """
    samples: np.ndarray
    sample_rate: float
    periodic: bool = False
    frequency: Optional[float] = None
    frequency_error: float = 0.

    @property
    def duration(self) -> float:
        """Seconds"""
        return len(self.samples) / self.sample_rate


@dataclasses.dataclass
class Waveform(ABC):
    """Base class of the waveforms. Subclass it with a dataclass, set ``name`` and register it"""
    name: ClassVar[str] = ''
    title: ClassVar[str] = ''  # label in a list of waveforms, ``name`` if empty
    periodic: ClassVar[bool] = False  # True: :meth:`realize` gives one period to repeat

    def __post_init__(self):
        for field in self._parameters():
            value = getattr(self, field.name)
            unit = field.metadata['unit']
            if unit is not None:
                value = float(value.m_as(unit)) if isinstance(value, Q_) else float(value)
                lower, upper = field.metadata['min'], field.metadata['max']
                if (lower is not None and value < lower) or (upper is not None and value > upper):
                    raise ValueError(f'{self.name}: {field.name} = {value} {unit} is out of its limits '
                                     f'({lower}, {upper})')
                setattr(self, field.name, value)

    # ---- the description as settings
    @classmethod
    def _parameters(cls) -> list[dataclasses.Field]:
        return [field for field in dataclasses.fields(cls) if 'unit' in field.metadata]

    @classmethod
    def params(cls) -> list[dict]:
        """The parameters of this waveform as a list of settings dictionaries (pyqtgraph Parameter syntax)"""
        params = []
        for field in cls._parameters():
            meta = field.metadata
            param = {'title': meta['title'] or field.name, 'name': field.name, 'value': field.default,
                     'tip': meta['tip']}
            if meta['unit'] is None:
                param['type'] = 'str'
            else:
                dimensionless = meta['unit'] in ('dimensionless', 'deg')  # no SI prefix (k, m) in front of these
                param.update(type='float', suffix='' if meta['unit'] == 'dimensionless' else meta['unit'],
                             siPrefix=not dimensionless)
                for key in ('min', 'max'):
                    if meta[key] is not None:
                        param[key] = meta[key]
            params.append(param)
        return params

    @classmethod
    def from_settings(cls, group) -> 'Waveform':
        """Build the waveform from a settings group (a Parameter) holding the children of :meth:`params`"""
        return cls(**{field.name: group[field.name] for field in cls._parameters()})

    # ---- the samples
    def n_samples(self, sample_rate: float) -> int:
        """Number of samples of a waveform defined by its ``duration`` (at least 2)"""
        return max(2, int(round(getattr(self, 'duration') * sample_rate)))

    @abstractmethod
    def _realize(self, sample_rate: float) -> tuple[np.ndarray, Optional[float]]:
        """The samples and, for a periodic waveform, the frequency really generated"""

    def realize(self, sample_rate: Union[float, Q_]) -> RealizedWaveform:
        """The samples of the waveform for ``sample_rate`` (Hz, or a pint quantity)"""
        sample_rate = float(sample_rate.m_as('Hz')) if isinstance(sample_rate, Q_) else float(sample_rate)
        if sample_rate <= 0:
            raise ValueError('The sample rate should be positive')
        samples, frequency = self._realize(sample_rate)
        requested = getattr(self, 'frequency', None)
        return RealizedWaveform(np.asarray(samples, dtype=float), sample_rate, self.periodic, frequency,
                                0. if frequency is None else frequency - requested)


class WaveformFactory(ObjectFactory):
    """Factory class registering and creating the waveforms by name

    ``@WaveformFactory.register('sine')`` on a :class:`Waveform` dataclass registers it and gives it its ``name``.
    """

    @classmethod
    def register(cls, key: str):
        def inner_wrapper(wrapped_class: Type[Waveform]) -> Type[Waveform]:
            wrapped_class.name = key
            return super(WaveformFactory, cls).register(key)(wrapped_class)
        return inner_wrapper

    @classmethod
    def names(cls) -> list[str]:
        """Names of the registered waveforms, sorted as the form modules are imported"""
        return list(cls._builders.get(cls.__name__, {}))

    @classmethod
    def get_class(cls, key: str) -> Type[Waveform]:
        waveform_class = super().get_class(key)
        if waveform_class is None:
            raise KeyError(f'Unknown waveform {key}, available: {cls.names()}')
        return waveform_class

    def get(self, name: str, **parameters) -> Waveform:
        """Create the waveform registered as ``name`` from its parameters (numbers or pint quantities)"""
        return self.get_class(name)(**parameters)


# ---- helpers of the periodic waveforms
def _period(frequency: float, sample_rate: float) -> tuple[int, float]:
    """Number of samples of a period and the frequency that is really generated with it

    A looped buffer holds a whole number of periods, so the frequency is the one of the closest whole number of
    samples per period.
    """
    if frequency <= 0:
        raise ValueError('The frequency should be positive')
    if frequency > sample_rate / 2:
        raise ValueError(f'The frequency {frequency} Hz is above half the sample rate {sample_rate} Hz')
    n = int(round(sample_rate / frequency))
    return n, sample_rate / n


def _phase(n: int, phase_deg: float) -> np.ndarray:
    """The position in the period (0 to 1, going around) of each of the n samples"""
    return (np.arange(n) / n + phase_deg / 360.) % 1.
